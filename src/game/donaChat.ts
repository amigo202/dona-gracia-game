export function getChatEndpoint(): string | null {
  const envUrl = (import.meta.env.VITE_CHAT_ENDPOINT as string | undefined)?.trim();
  if (envUrl) return envUrl;
  if (typeof window !== "undefined") {
    const w = window as unknown as { __DG_CHAT_ENDPOINT__?: string };
    if (typeof w.__DG_CHAT_ENDPOINT__ === "string" && w.__DG_CHAT_ENDPOINT__.trim()) {
      return w.__DG_CHAT_ENDPOINT__.trim();
    }
  }
  return null;
}

const CITY_BY_SLUG: Record<string, string> = Object.fromEntries(
  screens.slice(1).map(s => [s.slug, s.city]),
);

export function initialGreeting(stationSlug?: string): string {
  if (stationSlug && CITY_BY_SLUG[stationSlug]) {
    const city = CITY_BY_SLUG[stationSlug];
    if (stationSlug === 'tiberias') {
      return 'שלום לך. את נמצאת כעת בתחנת טבריה — החזון שליווה אותי מרחוק. אפשר לשאול אותי כאן על החלום לשקם את העיר, או על כל תחנה אחרת במסע.';
    }
    return `שלום לך. את נמצאת כעת בתחנת ${city}. אפשר לשאול אותי מה קרה כאן, מה היו השיקולים שלי, או על כל תחנה אחרת במסעי.`;
  }
  return 'שלום לך. אני דונה גרציה. עברתי מסע ארוך מליסבון ועד קושטא, עם מבט מתמיד אל טבריה. מה תרצי לשאול אותי?';
}

