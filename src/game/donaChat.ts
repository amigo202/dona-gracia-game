    lisbon: 'למה התחתנת גם בסתר וגם בכנסייה?',
    antwerp: 'איך ניהלת את העסקים והצלת אנוסים?',
    venice: 'איך השתחררת מהמעצר בוונציה?',
    ferrara: 'מה השתנה כשהגעת לפררה?',
