function stationFallback(slug?: string): string {
  if (slug && extra[slug]) {
    const city = CITY_BY_SLUG[slug] || '';
    const facts = extra[slug].facts.map(f => f.text).slice(0, 2).join(' ');
    return `ב${city} למדתי שכל החלטה נושאת מחיר. ${facts}`;
  }
  const list = SLUGS.map(s => CITY_BY_SLUG[s]).join(', ');
  return `המסע שלי עבר דרך ${list}. תוכלי לשאול אותי על כל אחת מהתחנות האלה, על החיים כאנוסים, על ניהול העסקים, על חרם אנקונה או על החזון שלי בטבריה.`;
}

export function localDonaReply(question: string, stationSlug?: string): string {
  const q = question.trim();
  if (!q) return initialGreeting(stationSlug);

  for (const rule of RULES) {
    if (rule.keys.test(q)) {
      return rule.reply();
    }
  }
  if (/כאן|התחנה|המקום|פה|עכשיו|מה היה/.test(q) && stationSlug) {
    return stationFallback(stationSlug);
  }
  return stationFallback(stationSlug);
}

export async function askDona(
  question: string,
  history: ChatMessage[],
  stationSlug?: string,
): Promise<{ reply: string; mode: 'remote' | 'local' }> {
  const endpoint = getChatEndpoint();
  if (endpoint) {
    try {
      const resp = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message: question,
          station: stationSlug || null,
          history: history.slice(-6).map(m => ({
            role: m.role === 'dona' ? 'assistant' : 'user',
            content: m.text,
          })),
        }),
      });
      if (resp.ok) {
        const data = await resp.json();
        const text =
          data?.reply ||
          data?.answer ||
          data?.text ||
          data?.choices?.[0]?.message?.content;
        if (typeof text === 'string' && text.trim()) {
          return { reply: text.trim(), mode: 'remote' };
        }
      }
    } catch {
      /* חזרה למענה מבוסס־מקורות במקרה שהשרת לא זמין */
    }
  }
  return { reply: localDonaReply(question, stationSlug), mode: 'local' };
}
